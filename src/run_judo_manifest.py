def write_native_runtime_attestation(path: Path, value: Mapping[str, Any]) -> None:
    payload = json.dumps(
        dict(value), ensure_ascii=False, indent=2, sort_keys=True, allow_nan=False
    ) + "\n"
    if path.exists():
        if path.read_text(encoding="utf-8") != payload:
            raise RuntimeError(f"native runtime attestation differs on resume: {path}")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(payload, encoding="utf-8")
    temporary.replace(path)


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    with path.open("r", encoding="utf-8") as handle:
        for line_number, raw in enumerate(handle, 1):
            if not raw.strip():
                continue
            row = json.loads(raw)
            if not isinstance(row, dict):
                raise ValueError(f"expected object at {path}:{line_number}")
            rows.append(row)
    return rows


def system_prompt(structure: str, grid_size: int) -> str:
    header = (
        "You are a helpful assistant for industrial quality control tasks. "
        "The user asks a question, and the Assistant solves it.\n"
        f"The query image is divided into a grid of {grid_size}×{grid_size} patches. "
        "Patch coordinates are (row, col) and both row and col start from 1 "
        "(top‑left patch is (1,1)).\n\n"
    )
    clauses = {
        "direct_answer": "Respond only as <answer>A|B|C|D</answer>.\n",
        "think_answer": (
            "Always respond in this exact order: "
            "<think>Grounded reasoning.</think><answer>A|B|C|D</answer>.\n"
        ),
        "seg_answer": (
            "Always respond in this exact order: <seg>anomaly patches, or None</seg>"
            "<answer>A|B|C|D</answer>.\n"
        ),
        "think_seg_answer": (
            "Always respond in this exact order: <think>Grounded reasoning.</think>"
            "<seg>anomaly patches, or None</seg><answer>A|B|C|D</answer>.\n"
        ),
        "seg_think_answer": (
            "Always respond in this exact order and format:\n"
            "1) <seg> The anomalous region patch list (use (r,c) and "
            "(r,c_start)-(r,c_end) for contiguous columns). If there is not anomaly, "
            "respond 'None'. </seg>\n"
            "2) <think> Provide your detailed reasoning so that it leads to the correct answer. </think>\n"
            "3) <answer>A|B|C|D</answer>\n"
        ),
    }
    if structure not in clauses:
        raise ValueError(f"unknown output structure: {structure}")
    return header + clauses[structure]


def load_rgb(path: Path, size: int) -> Image.Image:
    with Image.open(path) as image:
        return image.convert("RGB").resize((size, size), Image.Resampling.LANCZOS)


def resolve_asset_path(data_root: Path, value: Any, field: str, sample_id: Any) -> Path:
    if not isinstance(value, str) or not value:
        raise ValueError(f"{sample_id}: {field} must be a non-empty relative path")
    relative = Path(value)
    if relative.is_absolute():
        raise ValueError(f"{sample_id}: absolute {field} path is forbidden: {value}")
    root = data_root.expanduser().resolve(strict=True)
    candidate = (root / relative).resolve(strict=True)
    try:
        candidate.relative_to(root)
    except ValueError as error:
        raise ValueError(f"{sample_id}: {field} escapes data root: {value}") from error
    if not candidate.is_file():
        raise ValueError(f"{sample_id}: {field} is not a regular file: {candidate}")
    return candidate


def grid_cells(mask_path: Path, grid_size: int, coverage_threshold: float, size: int) -> set[tuple[int, int]]:
    with Image.open(mask_path) as mask:
        array = np.asarray(
            mask.convert("L").resize((size, size), Image.Resampling.NEAREST)
        ) > 0
    cells: set[tuple[int, int]] = set()
    edges = np.linspace(0, size, grid_size + 1, dtype=int)
    for row in range(grid_size):
        for column in range(grid_size):
            patch = array[edges[row] : edges[row + 1], edges[column] : edges[column + 1]]
            if patch.size and float(patch.mean()) >= coverage_threshold:
                cells.add((row + 1, column + 1))
    return cells


def compress_cells(cells: set[tuple[int, int]]) -> str:
    if not cells:
        return "None"
    pieces: list[str] = []
    by_row: dict[int, list[int]] = {}
    for row, column in sorted(cells):
        by_row.setdefault(row, []).append(column)
    for row, columns in sorted(by_row.items()):
        start = previous = columns[0]
        for column in columns[1:] + [columns[-1] + 2]:
            if column == previous + 1:
                previous = column
                continue
            pieces.append(
                f"({row},{start})" if start == previous else f"({row},{start})-({row},{previous})"
            )
            start = previous = column
    return ", ".join(pieces)


def resolve_prefix(row: dict[str, Any], data_root: Path, grid_size: int, threshold: float, image_size: int) -> str:
    prefix = row.get("forced_prefix")
    if prefix == "__DERIVE_FROM_MASK__":
        mask_image = row.get("mask_image")
        if not mask_image:
            raise ValueError(f"GT prefix requested without mask for {row.get('diagnostic_id')}")
        cells = grid_cells(
            resolve_asset_path(
                data_root,
                mask_image,
                "mask_image",
                row.get("diagnostic_id", row.get("sample_id")),
            ),
            grid_size,
            threshold,
            image_size,
        )
        content = compress_cells(cells)
    else:
        text = str(prefix or "")
        if not text:
            return ""
        match = SEG_PATTERN.search(text)
        content = match.group(1).strip() if match else text.strip()
    # Match JUDO's observed SFT/AR surface form exactly.  Spacing around the
    # segment content is tokenically meaningful for conditional continuations.
    return f"<seg> {content} </seg>"


def user_payload(row: dict[str, Any], official_typo: bool) -> str:
    options_text = row.get("options_text")
    if options_text is None:
        # Some external causal panels preserve the canonical option mapping but
        # omit MMAD's redundant rendered string.  Reconstruct that string with
        # the byte-exact MMAD surface instead of mutating the frozen manifest.
        options = row.get("options")
        if not isinstance(options, dict) or list(options) != ["A", "B", "C", "D"]:
            raise ValueError("options_text is absent and options are not ordered A-D")
        if any(not isinstance(options[key], str) or not options[key] for key in "ABCD"):
            raise ValueError("options_text is absent and an option is not a non-empty string")
        options_text = "".join(f"{key}. {options[key]}\n" for key in "ABCD")
    elif not isinstance(options_text, str) or not options_text:
        raise ValueError("options_text must be a non-empty string")
    lead = "n" if official_typo else "\n"
    return (
        f"{lead}First image = QUERY; Second image = NORMAL template.\n"
        f"Question: {row['question']}\n{options_text}"
    )


def prepare_prompt(
    row: dict[str, Any],
    processor: Any,
    data_root: Path,
    grid_size: int,
    image_size: int,
    coverage_threshold: float,
    official_typo: bool,
) -> tuple[str, list[Image.Image], str]:
    structure = str(row.get("output_structure") or "seg_think_answer")
    continuation = str(row.get("generation_continuation") or structure)
    visible = row.get("visible_images", ["query", "reference"])
    visible = list(visible)
    content: list[dict[str, Any]] = []
    images: list[Image.Image] = []
    sample_id = row.get("diagnostic_id", row.get("sample_id"))
    if "query" in visible:
        content.append({"type": "image"})
        images.append(
            load_rgb(resolve_asset_path(data_root, row.get("image"), "image", sample_id), image_size)
        )
    if "reference" in visible:
        content.append({"type": "image"})
        images.append(
            load_rgb(
                resolve_asset_path(
                    data_root,
                    row.get("template_image"),
                    "template_image",
                    sample_id,
                ),
                image_size,
            )
        )
    content.append({"type": "text", "text": user_payload(row, official_typo)})
    system_text = system_prompt(continuation, grid_size)
    if row.get("diagnostic_family") == "reasoning_budget" and row.get("max_reasoning_tokens"):
        budget = int(row["max_reasoning_tokens"])
        system_text += (
            f"Use approximately {budget} tokens inside <think>; keep checking both images "
            "and do not emit <answer> before completing that reasoning budget.\n"
        )
    messages = [
        {"role": "system", "content": system_text},
        {"role": "user", "content": content},
    ]
    prompt = processor.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
    prefix = resolve_prefix(row, data_root, grid_size, coverage_threshold, image_size)
    # A closed <seg> alone is a learned stopping boundary for JUDO and can yield
    # EOS immediately.  A segmentation-mediator intervention must condition the
    # downstream reasoning, so start (but do not supply) the <think> stage.
    if row.get("diagnostic_family") == "segmentation_prefix" and prefix:
        prefix += "\n<think> "
    return prompt + prefix, images, prefix


def batched(values: list[Any], size: int) -> Iterable[list[Any]]:
    for start in range(0, len(values), size):
        yield values[start : start + size]


def set_ptx_question_predicates(
    model: Any,
    adapter: Any,
    tokenizer: Any,
    rows: list[dict[str, Any]],
) -> None:
    """Apply the checkpoint-locked question-only PTX predicate protocol."""

    questions = [str(row.get("question", "")).strip() for row in rows]
    if any(not value for value in questions):
        raise ValueError("PTX inference requires a non-empty question field")
    encoded = tokenizer(
        questions,
        add_special_tokens=False,
        padding=True,
        return_tensors="pt",
    )
    device = next(model.parameters()).device
    input_ids = encoded["input_ids"].to(device)
    attention = encoded["attention_mask"].to(device=device, dtype=torch.float32)
    if bool(attention.sum(dim=1).eq(0).any()):
        raise ValueError("PTX inference predicate tokenization is empty")
    with torch.no_grad():
        embeddings = model.get_input_embeddings()(input_ids).detach().float()
    predicate = (embeddings * attention.unsqueeze(-1)).sum(dim=1) / attention.sum(
        dim=1, keepdim=True
    )
    if predicate.ndim != 2 or predicate.shape[1] != int(adapter.hidden_size):
        raise RuntimeError("PTX inference predicate/carrier dimension mismatch")
    adapter.set_predicate_embeddings(predicate.detach())


def extract_answer(text: str) -> str:
    match = ANSWER_PATTERN.search(text)
    if match:
        return match.group(1).upper()
    matches = re.findall(r"\b([A-D])\b", text.upper())
    return matches[-1] if matches else "X"


def extract_answer_strict(text: str) -> str:
    match = ANSWER_PATTERN.search(text)
    return match.group(1).upper() if match else "X"


