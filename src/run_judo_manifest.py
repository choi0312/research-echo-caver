def native_adapter_artifact_identity(kind: str, directory: Path) -> dict[str, Any]:
    """Validate one native CAVER/RIFT/PACE/LIFT checkpoint without importing model code."""

    if kind not in {"caver", "rift", "pace", "ptx", "lift", "moment", "absorb"}:
        raise ValueError(f"unsupported native adapter kind: {kind!r}")
    expanded = directory.expanduser()
    if expanded.is_symlink():
        raise ValueError(f"native adapter directory must not be a symlink: {expanded}")
    root = expanded.resolve(strict=True)
    if not root.is_dir():
        raise ValueError(f"native adapter directory is not a directory: {root}")
    identity_path = _strict_native_path(
        root / "native_deep_residual_identity.json", "native adapter identity"
    )
    weights_path = _strict_native_path(
        root / "native_deep_residual.safetensors", "native adapter weights"
    )
    checkpoint_files = sorted(
        path.resolve()
        for path in root.rglob("*")
        if path.is_file() and path.suffix.casefold() in {".safetensors", ".bin", ".pt", ".pth"}
    )
    if checkpoint_files != [weights_path]:
        raise ValueError(
            "native adapter directory must contain exactly one checkpoint: "
            f"{[str(path) for path in checkpoint_files]}"
        )
    if any(path.is_symlink() for path in root.rglob("*")):
        raise ValueError("native adapter directory must not contain symlinks")

    identity = json.loads(identity_path.read_text(encoding="utf-8"))
    if not isinstance(identity, dict) or identity.get("schema_version") != NATIVE_ADAPTER_SCHEMA:
        raise ValueError("native adapter identity schema mismatch")
    weights_sha = sha256_file(weights_path)
    if identity.get("weights_sha256") != weights_sha:
        raise ValueError("native adapter weights SHA-256 mismatch")
    parameter_count = _positive_int(identity.get("parameter_count"), "parameter_count")
    statistics = identity.get("statistics")
    if not isinstance(statistics, Mapping):
        raise ValueError("native adapter identity lacks statistics")
    expected_architecture = {
        "caver": CAVER_ARCHITECTURE,
        "rift": RIFT_ARCHITECTURE,
        "pace": PACE_ARCHITECTURE,
        "ptx": PTX_ARCHITECTURE,
        "lift": LIFT_ARCHITECTURE,
        "moment": MOMENT_ARCHITECTURE,
        "absorb": ABSORB_ARCHITECTURE,
    }[kind]
    if statistics.get("architecture") != expected_architecture:
        raise ValueError(
            f"native adapter architecture mismatch for {kind}: "
            f"{statistics.get('architecture')!r}"
        )
    decision_protocol = identity.get("decision_protocol")
    phase_protocol = identity.get("phase_protocol")
    if not isinstance(decision_protocol, Mapping) or not isinstance(phase_protocol, Mapping):
        raise ValueError("native adapter token protocol is absent")
    lineage = _native_lineage(kind, identity, statistics)
    payload = {
        "schema_version": "judo-native-adapter-artifact-identity-v1",
        "native_adapter_kind": kind,
        "architecture": expected_architecture,
        "identity_file_sha256": sha256_file(identity_path),
        "weights_sha256": weights_sha,
        "parameter_count": parameter_count,
        "lineage": lineage,
    }
    return {
        **payload,
        "adapter_identity_sha256": canonical_sha256(payload),
        "adapter_directory": str(root),
        "identity_file": identity_path.name,
        "weight_file": weights_path.name,
    }


def native_token_protocol(tokenizer: Any) -> tuple[list[int], str, dict[str, Any], dict[str, Any]]:
    variants = [
        [int(value) for value in tokenizer.encode(f"<answer>{letter}", add_special_tokens=False)]
        for letter in "ABCD"
    ]
    common = 0
    for values in zip(*variants):
        if len(set(values)) != 1:
            break
        common += 1
    if common < 1 or any(len(value) <= common for value in variants):
        raise RuntimeError(f"invalid native answer decision boundary: {variants}")
    prefix = variants[0][:common]
    candidates = [value[common] for value in variants]
    if len(set(candidates)) != 4:
        raise RuntimeError(f"native answer branches are not unique: {variants}")
    prefix_text = tokenizer.decode(
        prefix, skip_special_tokens=False, clean_up_tokenization_spaces=False
    )
    if [int(value) for value in tokenizer.encode(prefix_text, add_special_tokens=False)] != prefix:
        raise RuntimeError("native answer decision prefix does not round-trip")
    decision = {
        "variants": variants,
        "common_prefix_ids": prefix,
        "common_prefix_text": prefix_text,
        "first_branch_token_ids": candidates,
        "first_branch_token_text": [tokenizer.decode([value]) for value in candidates],
    }
    phase = {
        "assistant_prefix_ids": [
            int(value)
            for value in tokenizer.encode("<|im_start|>assistant\n", add_special_tokens=False)
        ],
        "seg_start_ids": [
            int(value) for value in tokenizer.encode("<seg>", add_special_tokens=False)
        ],
    }
    return prefix, prefix_text, decision, phase


